"""Synthetic arithmetic data and prompt formatting.

Shared by train.py and evaluate.py so that every run works from the exact
same data and prompt format. The examples themselves are generated by
src/arithmetic.py; this module holds the (global) task settings, which are
loaded from the `arithmetic:` block of a config via configure().
"""

import re

from src.arithmetic import format_mul, generate_arithmetic, generate_multiplication

SETTINGS = {
    "ops": "addsub",  # "addsub" (addition and subtraction) or "mul" (multiplication)
    "min_digits": 2,  # digits of each operand in the training split
    "max_digits": 8,
    "test_min_digits": None,  # test split digits; default to min/max_digits
    "test_max_digits": None,
    "n_train": 5000,
    "n_test": 300,
}

_ANSWER_TAG_RE = re.compile(r"####\s*(-?[0-9][0-9,]*(?:\.[0-9]+)?)")


def configure(**settings) -> None:
    """Override task settings (typically `cfg["arithmetic"]` from a config)."""
    unknown = set(settings) - set(SETTINGS)
    if unknown:
        raise ValueError(f"Unknown arithmetic settings: {sorted(unknown)}")
    if settings.get("ops", SETTINGS["ops"]) not in ("addsub", "mul"):
        raise ValueError("arithmetic.ops must be 'addsub' or 'mul'")
    SETTINGS.update(settings)


def load_split(split: str) -> list[dict]:
    """Return the "train" or "test" split as [{"question", "answer"}, ...].
    Answers end with "#### <number>"; no test question appears in train."""
    n = SETTINGS["n_train"] if split == "train" else SETTINGS["n_test"]
    lo, hi = SETTINGS["min_digits"], SETTINGS["max_digits"]
    if split == "test":
        lo = SETTINGS["test_min_digits"] or lo
        hi = SETTINGS["test_max_digits"] or hi
    if SETTINGS["ops"] == "mul":
        return generate_multiplication(split, n, lo, hi)
    return generate_arithmetic(split, n, lo, hi)


def extract_gold_answer(answer_text: str) -> str:
    """Extract the final numeric answer from a reference solution (the part
    after "####"), stripping thousands separators.
    """
    match = _ANSWER_TAG_RE.search(answer_text)
    if not match:
        raise ValueError(f"Could not find '#### <answer>' in: {answer_text!r}")
    return match.group(1).replace(",", "")


def build_training_target(answer_text: str) -> str:
    """The completion the model is trained to produce."""
    return answer_text.strip()


def _fewshot_example() -> str:
    """One fixed worked example shown before every question."""
    if SETTINGS["ops"] == "mul":
        return f"Question: What is 397 x 4429?\nAnswer: {format_mul(397, 4429)}"
    return "Question: What is 4821 + 3079?\nAnswer: 4821 + 3079 = 7900\n#### 7900"


def build_prompt(question: str) -> str:
    """Build the fixed prompt for a single question.

    Same prompt format must be used at training and evaluation time so
    results are comparable across submissions.
    """
    return f"{_fewshot_example()}\n\nQuestion: {question}\nAnswer:"
